// Freeze the pre-"Walk-in" public kit for the super admin portal (/mes, /messages).
// Rewrites the old www.css + resources.css so every rule only matches inside
// .www-legacy (set in _app on those routes), keeping specificity unchanged via :where().
// Usage: node scripts/scope-www-legacy.js <projectDir> <out> <in...>
const path = require("path");
const fs = require("fs");
const [, , projectDir, outFile, ...inFiles] = process.argv;
const postcss = require(path.resolve(projectDir, "node_modules", "postcss"));

const SCOPE = ".www-legacy";
function scopeSelector(sel) {
  const s = sel.trim();
  if (!s) return s;
  if (s === ":root") return SCOPE;
  if (/^(html|body)\b/.test(s)) return s; // global resets kept as they were
  if (/\.www(?![\w-])/.test(s)) return s.replace(/\.www(?![\w-])/g, SCOPE);
  if (s.startsWith(".js ")) return `.js :where(${SCOPE}) ${s.slice(4)}`;
  return `:where(${SCOPE}) ${s}`;
}
function insideKeyframes(node) {
  for (let p = node.parent; p; p = p.parent) if (p.type === "atrule" && /keyframes$/i.test(p.name)) return true;
  return false;
}
let out = "/* Generated by scripts/scope-www-legacy.js: the pre-Walk-in public kit, scoped to .www-legacy\n   (super admin portal: /mes, /messages). Do not edit by hand. */\n";
for (const f of inFiles) {
  const root = postcss.parse(fs.readFileSync(f, "utf8"));
  root.walkComments((c) => c.remove());
  root.walkRules((rule) => {
    if (insideKeyframes(rule)) return;
    rule.selectors = rule.selectors.map(scopeSelector);
  });
  out += root.toString() + "\n";
}
fs.writeFileSync(outFile, out);
console.log("wrote", outFile);
